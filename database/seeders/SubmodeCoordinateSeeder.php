    public function run(): void
    {
        foreach( Submode::all() as $submode ){
            foreach( ($this->coordinates[$submode->name]?? []) as $coordinate){
                    $coordinate = Coordinate::select('coordinate_id as id')
                                    ->where('x',$coordinate['x'])
                                    ->where('y',$coordinate['y'])
                                    ->first();

                    if( empty($coordinate) )
                        $coordinate = Coordinate::create([ 'x' => $coordinate['x'], 'y' => $coordinate['y'] ]);
                    
                    Submode_coordinate::create([ 'submode_id' => $submode->submode_id, 'coordinate_id' => $coordinate->id ]);
            }
        }
    }
    
